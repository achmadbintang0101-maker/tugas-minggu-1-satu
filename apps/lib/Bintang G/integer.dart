void main() {
  int a = 10;
  int b = 3;

  int sum = a + b;       // 13
  int difference = a - b; // 7
  int product = a * b;   // 30
  
  int division = a ~/ b; // 3 (Integer division drops the decimal)
  int remainder = a % b; // 1 (Modulo)
  
  a++;                   // 11 (Increment)
  b--;                   // 2  (Decrement)
}